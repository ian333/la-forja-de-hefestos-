/**
 * Catálogo del Premio Nobel de Física (1901-2024).
 *
 * 118 premios entregados desde 1901 a más de 220 personas. Cada entrada es
 * UNA lección potencial del módulo de física. Lo mismo que hicimos con
 * Economía pero a mayor escala — la física es la disciplina más antigua
 * del Nobel y la que ha movido más fronteras en el siglo XX.
 *
 * Los bloques NO son cronológicos: están agrupados por TEMA pedagógico
 * para que un alumno pueda seguir el hilo conceptual. Dentro de cada
 * bloque, el orden es cronológico para mostrar la evolución de la idea.
 *
 * `status: 'live'` significa que la masterclass ya está producida y enlaza
 * a `/masterclass.html?id=<classId>`. `status: 'pending'` aparece como card
 * en gris en el portal, próxima a producir.
 */

export type NobelStatus = 'live' | 'pending';

export interface PhysicsLaureate {
  /** Slug del premio. Usado como id de masterclass cuando esté live. */
  id: string;
  /** Año del premio. */
  year: number;
  /** Lista de premiados (1-3 personas). */
  laureates: string[];
  /** Bloque temático. Determina el color y el orden visual. */
  block: PhysicsBlock;
  /** Título corto de la lección — el "hook". */
  title: string;
  /** Subtítulo: qué premió oficialmente el comité (en español). */
  subtitle: string;
  /** Frase de impacto: qué cambia entender esto. */
  impact: string;
  /** Estado de producción. */
  status: NobelStatus;
  /** Si status === 'live', el classId del masterclass. */
  classId?: string;
}


/**
 * Cuenta cuántos premios están en cada estado.
 */
export function getPhysicsStats() {
  const total = PHYSICS_CATALOG.length;
  const live = PHYSICS_CATALOG.filter(n => n.status === 'live').length;
  const pending = total - live;
  return { total, live, pending };
}

/**
 * Agrupa los premios por bloque, en el orden definido en PHYSICS_BLOCKS.
 */
export function getPhysicsByBlock(): Array<{ block: PhysicsBlockMeta; entries: PhysicsLaureate[] }> {
  const ordered = [...PHYSICS_BLOCKS].sort((a, b) => a.order - b.order);
  return ordered.map(block => ({
    block,
    entries: PHYSICS_CATALOG
      .filter(n => n.block === block.id)
      .sort((a, b) => a.year - b.year),
  }));
}
